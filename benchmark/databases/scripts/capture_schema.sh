#!/usr/bin/env bash
# Capture each database's REAL schema after a fixture import.
#
# 3DCityDB v5's column names are not documented at the level needed to
# write scenario SQL in advance. Rather than guess them, we import a small
# fixture and read the schema back out of information_schema. The output is
# committed so the scenario SQL in Tasks 8 and 9 is written against
# verified reality.
set -euo pipefail

DATASET="${1:?usage: capture_schema.sh <path-to-.city.jsonl>}"
OUT_DIR="$(dirname "$0")/../docs"
mkdir -p "$OUT_DIR"

dump_schema() {
    local port="$1" schema="$2"
    PGPASSWORD=bench psql -h localhost -p "$port" -U bench -d bench -X -q <<SQL
\pset format aligned
\echo '## Tables and row counts'
SELECT table_name FROM information_schema.tables
 WHERE table_schema = '${schema}' ORDER BY table_name;
\echo ''
\echo '## Columns'
SELECT table_name, ordinal_position, column_name, data_type, is_nullable
  FROM information_schema.columns
 WHERE table_schema = '${schema}' ORDER BY table_name, ordinal_position;
\echo ''
\echo '## Indexes'
SELECT tablename, indexname, indexdef FROM pg_indexes
 WHERE schemaname = '${schema}' ORDER BY tablename, indexname;
SQL
}

{
    echo "# cjdb schema (captured)"
    echo
    echo "Generated by scripts/capture_schema.sh from ${DATASET}."
    echo "Do not hand-edit — regenerate instead."
    echo
    echo '```'
    dump_schema 55432 cjdb
    echo '```'
} > "$OUT_DIR/cjdb-schema.md"

{
    echo "# 3DCityDB v5 schema (captured)"
    echo
    echo "Generated by scripts/capture_schema.sh from ${DATASET}."
    echo "Do not hand-edit — regenerate instead."
    echo
    echo '```'
    dump_schema 55433 citydb
    echo '```'
} > "$OUT_DIR/3dcitydb-v5-schema.md"

echo "captured -> $OUT_DIR/{cjdb,3dcitydb-v5}-schema.md"
