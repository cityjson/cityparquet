//! The CityGML crates quantise a document at the step its CRS's axes
//! declare, from a table of steps generated from this crate's EPSG table,
//! since they cannot depend on it. This test is that table's generator and
//! its check: the steps must be the ones `cityparquet_schema::crs::axis_scale`
//! derives for every CRS the EPSG table holds, to the bit, or a package
//! converted from CityGML is quantised differently from the same data
//! converted any other way.
//!
//! After regenerating `epsg_projjson.json.gz`, run it with
//! `CITYGML_CRS_STEPS_WRITE=1` to rewrite the table.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

use cityparquet_schema::CityParquetError;
use cityparquet_schema::crs::{
    MM, NANO_DEGREE, axis_scale, resolve_to_projjson, vendored_keys, vendored_proj_version,
};

/// What `axis_scale` says of the CRS the EPSG table knows by `key`.
fn step(key: &str) -> Result<[f64; 3], String> {
    let projjson = resolve_to_projjson(key).unwrap();
    match axis_scale(&projjson) {
        Ok(scale) => Ok(scale),
        Err(CityParquetError::Schema(message)) => Err(message),
        Err(other) => panic!("{key}: {other}"),
    }
}

fn bits(scale: [f64; 3]) -> [u64; 3] {
    scale.map(f64::to_bits)
}

/// An `f64` as a Rust literal that reads back as the same bits.
fn literal(x: f64) -> String {
    let text = format!("{x:?}");
    assert_eq!(text.parse::<f64>().unwrap().to_bits(), x.to_bits(), "{text}");
    text
}

fn triple(scale: [f64; 3]) -> String {
    format!(
        "[{}, {}, {}]",
        literal(scale[0]),
        literal(scale[1]),
        literal(scale[2])
    )
}

/// The table `citygml-core` holds, as its source.
fn render() -> String {
    let mut codes = BTreeMap::new();
    let mut crs84 = BTreeMap::new();
    for key in vendored_keys() {
        match key.parse::<u32>() {
            Ok(code) => {
                codes.insert(code, step(key));
            }
            Err(_) => {
                crs84.insert(key, step(key).expect("CRS84 has a step"));
            }
        }
    }
    assert_eq!(
        crs84.keys().copied().collect::<Vec<_>>(),
        ["OGC:CRS84", "OGC:CRS84h"]
    );

    let mut steps: Vec<[f64; 3]> = Vec::new();
    let mut indexed = Vec::new();
    let mut refused = Vec::new();
    for (code, step) in codes {
        match step {
            Ok(scale) if bits(scale) == bits([MM; 3]) => {}
            Ok(scale) => {
                let i = match steps.iter().position(|s| bits(*s) == bits(scale)) {
                    Some(i) => i,
                    None => {
                        steps.push(scale);
                        steps.len() - 1
                    }
                };
                indexed.push((code, u8::try_from(i).unwrap()));
            }
            Err(message) => refused.push((code, message)),
        }
    }

    let mut out = String::new();
    writeln!(
        out,
        "//! Generated by `lib/cityparquet-rs/crates/core/tests/citygml_crs_steps.rs`\n\
         //! from `cityparquet-schema`'s EPSG table (PROJ {}): the quantisation\n\
         //! step of every CRS whose axes are not all metres. Do not edit; after the\n\
         //! EPSG table is regenerated, run that test with `CITYGML_CRS_STEPS_WRITE=1`.\n",
        vendored_proj_version()
    )
    .unwrap();
    writeln!(out, "/// The distinct steps, which [`CODES`] index.").unwrap();
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(
        out,
        "pub(super) const STEPS: [[f64; 3]; {}] = [",
        steps.len()
    )
    .unwrap();
    for scale in &steps {
        writeln!(out, "    {},", triple(*scale)).unwrap();
    }
    writeln!(out, "];\n").unwrap();
    writeln!(
        out,
        "/// EPSG codes and their step in [`STEPS`], by code. A code not here or in\n\
         /// [`REFUSED`] has a millimetre on each axis."
    )
    .unwrap();
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub(super) const CODES: &[(u32, u8)] = &[").unwrap();
    for row in indexed.chunks(8) {
        let row: Vec<String> = row.iter().map(|(c, i)| format!("({c}, {i})")).collect();
        writeln!(out, "    {},", row.join(", ")).unwrap();
    }
    writeln!(out, "];\n").unwrap();
    writeln!(
        out,
        "/// EPSG codes with an axis in a unit that has no step, by code, and why."
    )
    .unwrap();
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub(super) const REFUSED: &[(u32, &str)] = &[").unwrap();
    for (code, message) in &refused {
        writeln!(out, "    ({code}, {message:?}),").unwrap();
    }
    writeln!(out, "];\n").unwrap();
    writeln!(out, "/// `OGC:CRS84`'s step.").unwrap();
    writeln!(
        out,
        "pub(super) const CRS84: [f64; 3] = {};\n",
        triple(crs84["OGC:CRS84"])
    )
    .unwrap();
    writeln!(out, "/// `OGC:CRS84h`'s step.").unwrap();
    writeln!(
        out,
        "pub(super) const CRS84H: [f64; 3] = {};",
        triple(crs84["OGC:CRS84h"])
    )
    .unwrap();
    out
}

fn table_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../../citygml-rs/crates/core/src/crs/steps.rs")
}

#[test]
fn the_citygml_crates_hold_the_steps_of_this_crate_s_epsg_table() {
    let rendered = render();
    let path = table_path();
    if std::env::var_os("CITYGML_CRS_STEPS_WRITE").is_some() {
        std::fs::write(&path, &rendered).unwrap();
    }
    let committed = std::fs::read_to_string(&path).unwrap();
    assert!(
        committed == rendered,
        "{} is not generated from the EPSG table; rerun this test with \
         CITYGML_CRS_STEPS_WRITE=1",
        path.display()
    );
}

#[test]
fn every_crs_gets_the_same_step_from_the_citygml_crates() {
    assert_eq!(citygml::crs::MM.to_bits(), MM.to_bits());
    assert_eq!(
        citygml::crs::NANO_DEGREE.to_bits(),
        NANO_DEGREE.to_bits()
    );
    let mut checked = 0;
    for key in vendored_keys() {
        match (step(key), citygml::crs::scale_of(key)) {
            (Ok(ours), Ok(theirs)) => assert_eq!(bits(ours), bits(theirs), "{key}"),
            (Err(_), Err(_)) => {}
            (ours, theirs) => panic!("{key}: {ours:?} here, {theirs:?} in citygml-core"),
        }
        checked += 1;
    }
    assert!(checked > 7000, "{checked}");
}
